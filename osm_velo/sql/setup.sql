
-- ============================================================
-- OSM-Velo database setup
-- Safe to run repeatedly on an existing database.
-- Requires PostgreSQL and PostGIS.
-- ============================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS postgis;

-- ------------------------------------------------------------
-- Routes
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    route_hash TEXT UNIQUE,
    route geometry(LineString, 4326),
    point_count INTEGER NOT NULL DEFAULT 0,
    distance_m DOUBLE PRECISION NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Upgrade existing routes table.
ALTER TABLE public.routes
    ADD COLUMN IF NOT EXISTS route_hash TEXT;

ALTER TABLE public.routes
    ADD COLUMN IF NOT EXISTS route geometry(LineString, 4326);

ALTER TABLE public.routes
    ADD COLUMN IF NOT EXISTS point_count INTEGER NOT NULL DEFAULT 0;

ALTER TABLE public.routes
    ADD COLUMN IF NOT EXISTS distance_m DOUBLE PRECISION NOT NULL DEFAULT 0;

ALTER TABLE public.routes
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

CREATE UNIQUE INDEX IF NOT EXISTS routes_route_hash_unique
    ON public.routes (route_hash)
    WHERE route_hash IS NOT NULL;

-- ------------------------------------------------------------
-- GPS points
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.route_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL
        REFERENCES public.routes(id) ON DELETE CASCADE,
    sequence INTEGER NOT NULL,
    geom geometry(Point, 4326) NOT NULL,
    distance_from_start DOUBLE PRECISION NOT NULL DEFAULT 0,
    elevation_m DOUBLE PRECISION,
    slope_percent DOUBLE PRECISION,
    travel_direction_deg DOUBLE PRECISION,
    wind_effect_percent DOUBLE PRECISION,
    wind_effect_ms DOUBLE PRECISION,
    UNIQUE (route_id, sequence)
);

-- Upgrade existing route_points table.
ALTER TABLE public.route_points
    ADD COLUMN IF NOT EXISTS elevation_m DOUBLE PRECISION;

ALTER TABLE public.route_points
    ADD COLUMN IF NOT EXISTS slope_percent DOUBLE PRECISION;

ALTER TABLE public.route_points
    ADD COLUMN IF NOT EXISTS travel_direction_deg DOUBLE PRECISION;

ALTER TABLE public.route_points
    ADD COLUMN IF NOT EXISTS wind_effect_percent DOUBLE PRECISION;

ALTER TABLE public.route_points
    ADD COLUMN IF NOT EXISTS wind_effect_ms DOUBLE PRECISION;

CREATE INDEX IF NOT EXISTS route_points_route_id_idx
    ON public.route_points (route_id);

CREATE INDEX IF NOT EXISTS route_points_geom_idx
    ON public.route_points USING GIST (geom);

-- ------------------------------------------------------------
-- Elevation analysis summary
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.route_terrain_stats (
    route_id BIGINT PRIMARY KEY
        REFERENCES public.routes(id) ON DELETE CASCADE,
    min_elevation_m DOUBLE PRECISION,
    max_elevation_m DOUBLE PRECISION,
    min_elevation_distance_m DOUBLE PRECISION,
    max_elevation_distance_m DOUBLE PRECISION,
    total_gain_m DOUBLE PRECISION NOT NULL DEFAULT 0,
    total_loss_m DOUBLE PRECISION NOT NULL DEFAULT 0,
    min_slope_percent DOUBLE PRECISION,
    max_slope_percent DOUBLE PRECISION,
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ------------------------------------------------------------
-- Analysis job status
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.route_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL
        REFERENCES public.routes(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'pending',
    message TEXT,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS route_analyses_route_id_idx
    ON public.route_analyses (route_id);

COMMIT;
